-- Application schema for the workshop app. Django's framework tables (auth, sessions,
-- admin, content types) are created by Django itself; everything below is owned by Flyway.

CREATE TABLE app_item (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL,
    created_at  timestamptz  NOT NULL
);

CREATE TABLE app_employee (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     varchar(100) NOT NULL,
    last_name      varchar(100) NOT NULL,
    age            integer      NOT NULL CHECK (age >= 0),
    created_at     timestamptz  NOT NULL,
    supervisor_id  bigint       REFERENCES app_employee (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX app_employee_supervisor_id_idx ON app_employee (supervisor_id);

CREATE TABLE app_customer (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  varchar(100) NOT NULL,
    last_name   varchar(100) NOT NULL,
    email       varchar(254) NOT NULL UNIQUE,
    created_at  timestamptz  NOT NULL
);
CREATE INDEX app_customer_email_like_idx ON app_customer (email varchar_pattern_ops);

CREATE TABLE app_customerprofile (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone        varchar(40)  NOT NULL,
    address      varchar(255) NOT NULL,
    customer_id  bigint       NOT NULL UNIQUE REFERENCES app_customer (id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE app_product (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200)   NOT NULL,
    price       numeric(10, 2) NOT NULL,
    created_at  timestamptz    NOT NULL
);

CREATE TABLE app_order (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamptz NOT NULL,
    customer_id  bigint      NOT NULL REFERENCES app_customer (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX app_order_customer_id_idx ON app_order (customer_id);

CREATE TABLE app_orderitem (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity    integer        NOT NULL CHECK (quantity >= 0),
    unit_price  numeric(10, 2) NOT NULL,
    order_id    bigint         NOT NULL REFERENCES app_order (id) DEFERRABLE INITIALLY DEFERRED,
    product_id  bigint         NOT NULL REFERENCES app_product (id) DEFERRABLE INITIALLY DEFERRED,
    UNIQUE (order_id, product_id)
);
CREATE INDEX app_orderitem_order_id_idx   ON app_orderitem (order_id);
CREATE INDEX app_orderitem_product_id_idx ON app_orderitem (product_id);

-- Every write through the API is recorded as an Action with an append-only audit trail.
CREATE TABLE app_action (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id        varchar(32)  NOT NULL UNIQUE,
    type             varchar(100) NOT NULL,
    payload          jsonb        NOT NULL,
    idempotency_key  varchar(255) NOT NULL UNIQUE,
    request_hash     varchar(64)  NOT NULL,
    status           varchar(32)  NOT NULL,
    entity_type      varchar(50)  NOT NULL,
    entity_id        integer      CHECK (entity_id >= 0),
    created_at       timestamptz  NOT NULL
);
CREATE INDEX app_action_entity_idx ON app_action (entity_type, entity_id);

CREATE TABLE app_auditevent (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event       varchar(64) NOT NULL,
    "timestamp" timestamptz NOT NULL,
    action_id   bigint      NOT NULL REFERENCES app_action (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX app_auditevent_action_id_idx ON app_auditevent (action_id);
